"""Compare local retrieval variants and check a controlled claim-verification corpus."""

import argparse
import json
import math
from collections import defaultdict
from pathlib import Path
from statistics import mean
from tempfile import TemporaryDirectory
from time import perf_counter_ns
from typing import Any

from agent.config import REPO_ROOT
from evals.runners.smoke import GOLD_LABELS, SEED, read_jsonl
from rag.backends import CrossEncoderReranker, SentenceEmbeddings
from rag.corpus import Evidence, load_corpus
from rag.retriever import VARIANTS, Retriever, Variant
from rag.variants.v8_corrective import Ablation
from rag.verify import remove_unsupported, verify_claims
from scripts.data.build_world import build

RESULTS = REPO_ROOT / "evals" / "results"
PERSONAS = REPO_ROOT / "data" / "personas"
ABLATIONS: tuple[Ablation, ...] = ("without_bm25", "without_reranker", "without_retry")
METRICS = ("recall_at_5", "mrr", "ndcg_at_10")
METRIC_LABELS = dict(zip(METRICS, ("Recall@5", "MRR", "nDCG@10"), strict=True))


def scores(ranking: list[str], gold: dict[str, int]) -> tuple[float, float, float]:
    recall = len(gold.keys() & set(ranking[:5])) / len(gold)
    reciprocal_rank = next((1 / rank for rank, eid in enumerate(ranking, 1) if eid in gold), 0.0)
    discounted = sum(
        (2 ** gold.get(eid, 0) - 1) / math.log2(rank + 1)
        for rank, eid in enumerate(ranking[:10], 1)
    )
    ideal = sum(
        (2**grade - 1) / math.log2(rank + 1)
        for rank, grade in enumerate(sorted(gold.values(), reverse=True)[:10], 1)
    )
    return recall, reciprocal_rank, discounted / ideal


def verified_sample(corpora: dict[str, list[Evidence]]) -> dict[str, int]:
    """Test faithful text and two controlled unsupported variants from each of ten sources."""
    supported = detected = before = retained_unsupported = 0
    for index, corpus in enumerate(corpora.values()):
        candidates = [item for item in corpus if item.type == "case_study"][
            : 4 if index == 0 else 3
        ]
        for item in candidates:
            # Case studies generated by scripts.personas.render expose the work paragraph after
            # the headline and client context. The first sentence is an exact source statement.
            approach = item.text.split("\n\n")[2]
            quote = approach.split(". ", 1)[0].rstrip(".")
            faithful = quote + "."
            altered = quote + " while guaranteeing 100% customer success."
            unrelated = "I managed a NASA lunar mission from start to finish."
            draft = "\n\n".join((faithful, altered, unrelated))
            claims = verify_claims(draft, [item])
            outcomes = {claim.text.strip(): claim.status for claim in claims}
            supported += outcomes.get(faithful) == "supported"
            detected += sum(
                outcomes.get(text) in {"partly_supported", "unsupported"}
                for text in (altered, unrelated)
            )
            before += 2
            cleaned = remove_unsupported(draft, claims)
            retained_unsupported += sum(text in cleaned for text in (altered, unrelated))
    return {
        "faithful_supported": supported,
        "faithful_total": before // 2,
        "unsupported_identified": detected,
        "unsupported_before": before,
        "unsupported_after": retained_unsupported,
    }


def _summarize(
    observed: list[tuple[float, float, float]],
    timings: list[int] | None = None,
) -> dict[str, float | int]:
    result = {
        "jobs": len(observed),
        **{
            name: round(mean(column), 4)
            for name, column in zip(METRICS, zip(*observed, strict=True), strict=True)
        },
    }
    if timings:
        ordered = sorted(timings)
        index = math.ceil(0.95 * len(ordered)) - 1
        result["p95_ms_measured"] = round(ordered[index] / 1_000_000, 3)
    return result


def _rank_cases(
    cases: list[dict[str, Any]],
    jobs: dict[str, dict[str, Any]],
    retrievers: dict[str, Retriever],
    variant: Variant,
    ablation: Ablation | None,
) -> dict[str, Any]:
    groups: dict[str, list[tuple[float, float, float]]] = defaultdict(list)
    timings: list[int] = []
    misses = []
    for label in cases:
        job_id = label["job_id"]
        retriever = retrievers[label["persona"]]
        gold = {item["id"]: item["grade"] for item in label["gold_evidence"]}
        start = perf_counter_ns()
        hits = retriever.retrieve_job(jobs[job_id], k=10, variant=variant, ablation=ablation)
        timings.append(perf_counter_ns() - start)
        ids = [hit.evidence.id for hit in hits]
        measures = scores(ids, gold)
        requirements = len(jobs[job_id]["skills"])
        band = "four_or_more_requirements" if requirements >= 4 else "one_to_three_requirements"
        for group in (
            "all",
            f"persona/{label['persona']}",
            f"kind/{label['kind']}",
            f"scope/{band}",
        ):
            groups[group].append(measures)
        if measures[0] == 0:
            misses.append(
                {
                    "job_id": job_id,
                    "persona": label["persona"],
                    "kind": label["kind"],
                    "gold_ids": sorted(gold),
                    "retrieved_ids": ids[:5],
                }
            )

    return {
        "metrics": {
            group: _summarize(groups[group], timings if group == "all" else None)
            for group in sorted(groups)
        },
        "recall_at_5_zero_examples": misses[:20],
    }


def _fixtures(labels: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    with TemporaryDirectory(prefix="gigbid-retrieval-") as directory:
        root = Path(directory)
        build(seed=SEED, processed=root, dev_out=root / "dev.jsonl", test_out=root / "test.jsonl")
        rebuilt = {row["job_id"]: row for row in read_jsonl(root / "dev.jsonl")}
        for row in labels:
            current = rebuilt.get(row["job_id"])
            if not current or row["persona"] != current["persona"]:
                raise ValueError(f"Cannot match development label {row['job_id']}.")
            if row["label_source"] != "hand_verified" and row != current:
                raise ValueError(f"The construction label changed for {row['job_id']}.")
        return {
            job["job_id"]: {key: job[key] for key in ("title", "description", "skills")}
            for job in read_jsonl(root / "gigsim_world" / "jobs.jsonl")
            if job["job_id"] in rebuilt
        }


def evaluate(
    embedding_model: str | None = None, reranker_model: str | None = None
) -> dict[str, Any]:
    labels = read_jsonl(GOLD_LABELS)
    cases = [label for label in labels if label["gold_evidence"]]
    jobs = _fixtures(labels)
    corpora = {
        persona: load_corpus(PERSONAS / persona)
        for persona in sorted({label["persona"] for label in cases})
    }
    embedder = SentenceEmbeddings(embedding_model) if embedding_model else None
    reranker = CrossEncoderReranker(reranker_model) if reranker_model else None
    retrievers = {
        persona: Retriever(corpus, embedder=embedder, reranker=reranker)
        for persona, corpus in corpora.items()
    }
    backend = next(iter(retrievers.values()))
    measured = {
        variant: _rank_cases(cases, jobs, retrievers, variant, None) for variant in VARIANTS
    }
    ablated = {
        ablation: _rank_cases(cases, jobs, retrievers, "v8", ablation) for ablation in ABLATIONS
    }
    modes = measured | {f"v8_{stage}": summary for stage, summary in ablated.items()}
    best = min(modes, key=lambda mode: (-modes[mode]["metrics"]["all"]["ndcg_at_10"], mode))
    return {
        "dataset": "600 committed synthetic dev labels joined to rebuilt public job fields",
        "dataset_jobs": len(labels),
        "ranked_jobs": len(cases),
        "embedding_backend": backend.embedder.name,
        "reranking_backend": backend.reranker.name,
        "variants": measured,
        "corrective_ablations": ablated,
        "verified_claims": verified_sample(corpora),
        "highest_ndcg_mode": best,
    }


def to_report(results: dict[str, Any], command: str) -> dict[str, Any]:
    metrics = []
    summaries = {variant.upper(): summary for variant, summary in results["variants"].items()} | {
        "V8 " + stage.replace("_", " "): summary
        for stage, summary in results["corrective_ablations"].items()
    }
    for variant, summary in summaries.items():
        for name, label in METRIC_LABELS.items():
            metrics.append(
                {
                    "name": f"{variant} {label}",
                    "value": summary["metrics"]["all"][name],
                }
            )
    claims = results["verified_claims"]
    metrics.extend(
        (
            {
                "name": "Constructed unsupported claims detected",
                "value": claims["unsupported_identified"],
                "denominator": claims["unsupported_before"],
            },
            {
                "name": "Constructed unsupported claims retained after removal",
                "value": claims["unsupported_after"],
                "denominator": claims["unsupported_before"],
            },
            {
                "name": "Faithful source statements verified",
                "value": claims["faithful_supported"],
                "denominator": claims["faithful_total"],
            },
        )
    )
    return {
        "schema_version": 1,
        "experiment": "Development retrieval and claim verification",
        "scope": (
            f"{results['ranked_jobs']} gold-bearing synthetic dev jobs; relevance grades were used "
            f"only for scoring. Embeddings use {results['embedding_backend']}, reranking uses "
            f"{results['reranking_backend']}. The claim checks use constructed statements. "
            "Detailed group scores and local retrieval latency are in retrieval.dev.json."
        ),
        "command": command,
        "metrics": metrics,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=RESULTS)
    parser.add_argument(
        "--embedding-model", help="Path or cached ID of a sentence-transformers model"
    )
    parser.add_argument(
        "--reranker-model", help="Path or cached ID of a sentence-transformers cross-encoder"
    )
    args = parser.parse_args()
    custom = args.embedding_model or args.reranker_model
    if custom and args.output.resolve() == RESULTS:
        parser.error("For a custom model, choose a separate --output directory.")

    measured = evaluate(args.embedding_model, args.reranker_model)
    cmd = "uv run --extra rag python -m evals.runners.retrieval"
    if custom:
        cmd = (
            "uv run --extra rag --with sentence-transformers python -m evals.runners.retrieval "
            "with the same model arguments and a separate output directory"
        )
    args.output.mkdir(parents=True, exist_ok=True)
    for name, data in (
        ("retrieval.dev.json", measured),
        ("retrieval.report.json", to_report(measured, cmd)),
    ):
        text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        (args.output / name).write_text(text, encoding="utf-8", newline="\n")
    print(
        f"Scored {measured['ranked_jobs']} dev jobs. "
        f"Highest nDCG@10 was {measured['highest_ndcg_mode']}."
    )


if __name__ == "__main__":
    main()
